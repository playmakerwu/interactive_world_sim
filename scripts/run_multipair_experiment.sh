#!/usr/bin/env bash
# Launch 4 MPPI experiments in parallel on GPUs 4-7, one pair per GPU.
# Within each pair, 2 seeds run sequentially on the same GPU.
#
# Total: 8 runs. Expected wall time ~10 hours at N=100, 100 control_steps
# on an L40S (two sequential ~5h runs per GPU).
#
# Usage (run on cloud from repo root):
#   conda activate iws      # not strictly required; each tmux session
#                           # re-activates iws itself, but nice to verify
#   bash scripts/run_multipair_experiment.sh
#
# Monitor after launch:
#   tmux ls                                  # see all 4 sessions
#   tmux attach -t mppi_pair_A               # attach to one
#   tail -f outputs/mppi/multipair_cloud/pair_A_seed_0.log
#   nvidia-smi --query-gpu=index,memory.used,utilization.gpu --format=csv

set -u  # error on unset var. Intentionally NOT -e: one failing pair
        # should not abort the launcher before the others start.

# ── Config ─────────────────────────────────────────────────────────────
PAIRS=("A" "B" "C" "D")
GPUS=(4 5 6 7)
SEEDS=(0 1)
CONTROL_STEPS=100
OUTPUT_ROOT="outputs/mppi/multipair_cloud"
CONFIG="configs/mppi/default.yaml"
WM_CKPT="outputs/pusht_cam1/checkpoints/best.ckpt"
CATALOG="tests/goal_selection/pair_catalog.json"
CONDA_ENV="iws"

# ── Preflight ──────────────────────────────────────────────────────────
if [ -d "$OUTPUT_ROOT" ]; then
    echo "ERROR: $OUTPUT_ROOT already exists. Move or delete it first." >&2
    exit 1
fi
if [ ! -f "$CATALOG" ]; then
    echo "ERROR: $CATALOG not found. Run build_pair_catalog.py first." >&2
    exit 1
fi
if [ ! -f "$WM_CKPT" ]; then
    echo "ERROR: WM checkpoint not found at $WM_CKPT." >&2
    exit 1
fi
if ! command -v tmux &>/dev/null; then
    echo "ERROR: tmux not available in PATH." >&2
    exit 1
fi

mkdir -p "$OUTPUT_ROOT"
WORKDIR="$(pwd)"

echo "=== Multi-pair MPPI experiment launcher ==="
echo "Workdir:       $WORKDIR"
echo "Conda env:     $CONDA_ENV"
echo "Pairs:         ${PAIRS[*]}"
echo "GPUs:          ${GPUS[*]}"
echo "Seeds/pair:    ${SEEDS[*]}"
echo "Control steps: $CONTROL_STEPS"
echo "Output:        $OUTPUT_ROOT/"
echo ""

# ── Launch loop ────────────────────────────────────────────────────────
for i in "${!PAIRS[@]}"; do
    PAIR="${PAIRS[i]}"
    GPU="${GPUS[i]}"
    SESSION="mppi_pair_${PAIR}"

    # Extract start + goal from the catalog (single python invocation per pair).
    read -r START_HDF5 START_FRAME GOAL_PT < <(
        python -c "
import json, sys
d = json.load(open('$CATALOG'))
p = d['pair_$PAIR']
print(p['start']['hdf5_path'], p['start']['frame_idx'], p['goal']['state_pt_path'])
"
    )
    if [ -z "$START_HDF5" ] || [ -z "$GOAL_PT" ]; then
        echo "ERROR: failed to extract pair_$PAIR from $CATALOG." >&2
        exit 1
    fi

    LAUNCH_SCRIPT="$OUTPUT_ROOT/.launch_pair_${PAIR}.sh"
    cat > "$LAUNCH_SCRIPT" <<EOF
#!/usr/bin/env bash
# Auto-generated by run_multipair_experiment.sh for pair_$PAIR on GPU $GPU.
# Seeds run sequentially with ';' (not '&&') so seed 1 still runs if
# seed 0 fails — the two seeds are independent variance samples.

# Initialize conda in this non-interactive shell, then activate iws.
if [ -f "\$HOME/miniconda3/etc/profile.d/conda.sh" ]; then
    source "\$HOME/miniconda3/etc/profile.d/conda.sh"
elif [ -f "/opt/conda/etc/profile.d/conda.sh" ]; then
    source "/opt/conda/etc/profile.d/conda.sh"
fi
conda activate $CONDA_ENV || {
    echo "ERROR: conda activate $CONDA_ENV failed in tmux session. "    \\
         "Check that conda is installed and the env exists." >&2
    exit 1
}

export CUDA_VISIBLE_DEVICES=$GPU
cd "$WORKDIR"

echo "[pair $PAIR] launching on GPU $GPU at \$(date -Iseconds)"
echo "[pair $PAIR] start=$START_HDF5 frame=$START_FRAME goal=$GOAL_PT"
echo ""

EOF

    # Append one block per seed.
    for SEED in "${SEEDS[@]}"; do
        OUT_DIR="$OUTPUT_ROOT/pair_${PAIR}_seed_${SEED}"
        LOG="$OUTPUT_ROOT/pair_${PAIR}_seed_${SEED}.log"
        cat >> "$LAUNCH_SCRIPT" <<EOF
echo "[pair $PAIR seed $SEED] start \$(date -Iseconds)"
python -u scripts/run_mppi_v2.py \\
    --config $CONFIG \\
    --wm_ckpt $WM_CKPT \\
    --initial_hdf5 $START_HDF5 \\
    --initial_frame $START_FRAME \\
    --goal $GOAL_PT \\
    --output_dir $OUT_DIR \\
    --control_steps $CONTROL_STEPS \\
    --seed $SEED \\
    2>&1 | tee $LOG
echo "[pair $PAIR seed $SEED] end \$(date -Iseconds)"
echo ""

EOF
    done

    cat >> "$LAUNCH_SCRIPT" <<EOF
echo "[pair $PAIR] finished at \$(date -Iseconds). Session stays alive "
echo "            so tmux ls shows completion; Ctrl+b d to detach, "
echo "            tmux kill-session -t $SESSION to close."
# Keep shell open so tmux session stays around for inspection.
exec bash
EOF
    chmod +x "$LAUNCH_SCRIPT"

    echo "  pair_$PAIR → GPU $GPU, session '$SESSION', launch script $LAUNCH_SCRIPT"
    tmux new-session -d -s "$SESSION" "bash '$LAUNCH_SCRIPT'"
done

echo ""
echo "=== All 4 tmux sessions launched ==="
echo ""
echo "Monitor:"
echo "  tmux ls"
echo "  tmux attach -t mppi_pair_A"
echo "  tail -f $OUTPUT_ROOT/pair_A_seed_0.log"
echo "  watch -n 10 nvidia-smi --query-gpu=index,memory.used,utilization.gpu --format=csv"
echo ""
echo "Outputs will land at:"
for PAIR in "${PAIRS[@]}"; do
    for SEED in "${SEEDS[@]}"; do
        echo "  $OUTPUT_ROOT/pair_${PAIR}_seed_${SEED}/"
    done
done
